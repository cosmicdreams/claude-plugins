GATE_FIELDS = ('problem', 'proof', 'smallest', 'trigger', 'reviewer_value', 'not_verified')


class UpstreamError(RuntimeError):
    pass


def normalize_files(args):
    result = []
    iterator = iter(args)
    for arg in iterator:
        if arg == '--file':
            value = next(iterator, None)
            if not value or value.startswith('-'):
                raise UpstreamError('Use a readable comment file, not stdin or an option')
            arg = '--file=' + value
        if arg == '--file=-':
            raise UpstreamError('Comment stdin is unavailable; use an explicit file')
        result.append(arg)
    return result


def validate_post(path, projects, expected=None, maintainers_path=None):
    """Standalone enforcement of lib's upstream-post-guard contract."""
    if not path:
        raise UpstreamError('A post body and matching <body>.gate.json are required')
    path = Path(path)
    body = path.read_text()
    gate = json.loads(Path(str(path) + '.gate.json').read_text())
    if not isinstance(gate, dict):
        raise UpstreamError('Posting gate must be a JSON object')
    if any(not isinstance(gate.get(key), str) or not gate[key].strip() for key in GATE_FIELDS):
        raise UpstreamError('Posting gate needs all six written worth-it/proof/limits answers')
    if gate.get('body_sha256') != hashlib.sha256(body.encode()).hexdigest():
        raise UpstreamError('Post body changed after its worth-it gate was recorded')
    if expected is not None and body.strip() != expected:
        raise UpstreamError('Gate body must match the exact upstream command: ' + expected)
    if len(body.split()) > 150 or re.search(r'(?m)^\s{0,3}#{1,6}\s', body):
        raise UpstreamError('Posts must be at most 150 words with no headings')
    if re.search(r'(?i)\b(happy to|let me know|hope this helps|great catch|thanks for the review|in short|tl;?dr|generated with|generated by|co-authored-by|as an ai)\b|🤖', body):
        raise UpstreamError('Post fails upstream filler/attribution policy')
    if re.search(r'(?i)\b(separate from this|unrelated to (this|the)|outside (this|the) (mr|merge request|pr|pull request|fix)|not in this (mr|merge request|pr)|findings outside|choices worth a look)\b', body):
        raise UpstreamError('Side findings belong in a user follow-up, not an upstream post')
    registry = Path(maintainers_path) if maintainers_path else Path.home() / '.claude/upstream-maintainers.json'
    entries = json.loads(registry.read_text()) if registry.exists() else []
    if not isinstance(entries, list) or any(not isinstance(entry, dict) for entry in entries):
        raise UpstreamError('Maintainer registry is invalid; resolve it before posting')
    if any(entry.get('project') in projects for entry in entries) and gate.get('chris_approved') is not True:
        raise UpstreamError('This maintainer requires the user to approve the exact human-written post')


def canonical(value, project=None):
    """References retain the project: GitLab issue numbers are not globally unique."""
    if re.fullmatch(r'\d+', value):
        return {'id': int(value), 'project': project, 'backend': 'drupal', 'ref': value}
    match = re.fullmatch(r'https://www\.drupal\.org/project/([a-z0-9_]+)/issues/(\d+)(?:#.*)?', value)
    if match:
        return canonical(match[2], match[1])
    match = re.fullmatch(r'https://git\.drupalcode\.org/(.+)/-/work_items/(\d+)(?:#.*)?', value)
    if not match:
        match = re.fullmatch(r'(?:project/)?([a-z0-9_]+)#(\d+)', value)
        if match:
            path, nid = 'project/' + match[1], match[2]
        else:
            raise UpstreamError('Use an issue number, Drupal.org issue URL, project#id or work-item URL')
    else:
        path, nid = match[1], match[2]
    if not re.fullmatch(r'project/[a-z0-9_]+', path):
        raise UpstreamError('Unsupported work-item project path')
    return {'id': int(nid), 'project': path.split('/')[1], 'project_path': path,
            'backend': 'gitlab', 'ref': f'{path}#{nid}',
            'url': f'https://git.drupalcode.org/{path}/-/work_items/{nid}'}


def mr_reference(value):
    match = re.fullmatch(r'https://git\.drupalcode\.org/([a-zA-Z0-9_./-]+)/-/merge_requests/(\d+)(?:#.*)?', value)
    if not match:
        match = re.fullmatch(r'([a-zA-Z0-9_./-]+)!(\d+)', value)
    if not match or '..' in match[1].split('/'):
        raise UpstreamError('An explicit Drupal GitLab merge-request URL or project/path!id is required')
    return match[1], int(match[2])


def runtime_guard(path):
    path = Path(path).expanduser().resolve()
    branch = subprocess.check_output(['git', '-C', str(path), 'branch', '--show-current'], text=True).strip()
    root = subprocess.check_output(['git', '-C', str(path), 'rev-parse', '--show-toplevel'], text=True).strip()
    if str(path) != root or branch in ('', 'main', 'master') or path.parent.name != 'worktrees':
        raise UpstreamError('Runtime must be a dedicated feature worktree beside the actual main checkout')
    if not (path.parent / 'main').is_dir() or not (path / '.ddev/config.yaml').is_file():
        raise UpstreamError('Runtime needs its sibling main reference and DDEV configuration')
    def common(where):
        return subprocess.check_output(['git', '-C', str(where), 'rev-parse', '--path-format=absolute', '--git-common-dir'], text=True).strip()
    if common(path) != common(path.parent / 'main'):
        raise UpstreamError('Runtime and sibling main must be worktrees of the same repository')
    return path


class Runtime:
    def __init__(self, worktree, phar, output=None, timeout=45):
        self.worktree = runtime_guard(worktree)
        self.phar = phar
        self.output = Path(output) if output else None
        self.timeout = timeout
        self.receipts = []
        self.token = os.environ.get('DRUPALORG_GITLAB_TOKEN')
        if not self.token:
            try:
                result = subprocess.run(['glab', 'config', 'get', 'token', '--host', 'git.drupalcode.org'],
                                        capture_output=True, text=True, timeout=5)
                self.token = result.stdout.strip() if result.returncode == 0 else None
            except (OSError, subprocess.TimeoutExpired):
                pass

    def request(self, payload):
        payload.update(timeout=self.timeout, phar=self.phar, phar_sha256=SHA256, token=self.token)
        encoded = base64.b64encode(json.dumps(payload).encode()).decode()
        runner = Path(__file__).with_name('drupalorg_runner.php').read_text().replace('<?php', '', 1)
        # strict_types must be the first PHP statement, ahead of the request assignment.
        runner = runner.replace('declare(strict_types=1);', '', 1)
        program = "$request = json_decode(base64_decode('" + encoded + "'), true);\n" + runner
        scratch = self.worktree / '.ddev/drupalorg/requests'
        if not scratch.resolve().is_relative_to(self.worktree):
            raise UpstreamError('Runtime tooling directory must remain inside its worktree')
        ignored = subprocess.run(['git', 'check-ignore', '-q', str(scratch)], cwd=self.worktree)
        if ignored.returncode:
            raise UpstreamError('Run install first; transport scratch must be Git-ignored')
        scratch.mkdir(parents=True, mode=0o700, exist_ok=True)
        try:
            # DDEV exec does not forward host stdin. A 0600 temporary request on its
            # read-only config mount preserves arguments and keeps secrets out of argv.
            with tempfile.NamedTemporaryFile(mode='w', suffix='.php', dir=scratch) as request:
                request.write('<?php\n' + program)
                request.flush()
                container_file = '/mnt/ddev_config/drupalorg/requests/' + Path(request.name).name
                result = subprocess.run(['ddev', 'exec', '--skip-hooks', '--raw=true', 'php', container_file],
                                        cwd=self.worktree, capture_output=True, text=True, timeout=self.timeout + 15)
            if result.returncode:
                diagnostic = result.stderr.replace(self.token, '[redacted]') if self.token else result.stderr
                raise UpstreamError('DDEV runner failed: ' + diagnostic[:1000])
            try:
                data = json.loads(result.stdout)
            except ValueError as exc:
                raise UpstreamError('DDEV runner returned invalid JSON; inspect runtime PHP configuration') from exc
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise UpstreamError('DDEV runner unavailable or timed out') from exc
        receipt = {'at': datetime.datetime.now(datetime.timezone.utc).isoformat(),
                   'operation': {k: v for k, v in payload.items() if k not in ('token', 'files')},
                   'response': data}
        self.receipts.append(receipt)
        if self.output:
            self.output.mkdir(parents=True, mode=0o700, exist_ok=True)
            dest = self.output / 'evidence'
            dest.mkdir(mode=0o700, exist_ok=True)
            (dest / f'{len(self.receipts):03d}.json').write_text(json.dumps(receipt, indent=2) + '\n')
        return data

    def cli(self, command, *args, write=False):
        if command not in (WRITES if write else READS):
            raise UpstreamError('Command is outside this operation\'s permissions')
        text_output = command == 'project:release-notes'
        argv = [command, *normalize_files(args), *([] if text_output else ['--format=json']), '--no-interaction']
        files = {}
        for index, arg in enumerate(argv):
            if arg.startswith('--file=') and arg != '--file=-':
                files[str(index)] = base64.b64encode(Path(arg.split('=', 1)[1]).read_bytes()).decode()
                argv[index] = '--file=[transported]'
        data = self.request({'kind': 'cli', 'args': argv, 'files': files})
        if not data.get('ok'):
            raise UpstreamError(data.get('stderr') or data.get('error') or 'CLI command failed')
        if text_output:
            return {'format': 'text', 'text': data['stdout'],
                    'source_url': f'https://www.drupal.org/project/{args[0]}/releases/{args[1]}'}
        try:
            return json.loads(data['stdout'])
        except (ValueError, KeyError) as exc:
            raise UpstreamError('CLI output schema/format unsupported; inspect captured evidence') from exc

    def http(self, url, text=False):
        data = self.request({'kind': 'http', 'url': url})
        if not data.get('ok'):
            raise UpstreamError(f'Upstream HTTP {data.get("status", "unavailable")}: {url}')
        if text:
            return data['body']
        try:
            return json.loads(data['body'])
        except (ValueError, KeyError) as exc:
            raise UpstreamError('Upstream returned invalid JSON') from exc

    def pages(self, url, params=None, max_pages=30, stop_after=None):
        params = dict(params or {})
        params.update(per_page=100)
        items = []
        for page in range(1, max_pages + 1):
            query = dict(params, page=page)
            batch = self.http(url + '?' + urllib.parse.urlencode(query, doseq=True))
            if not isinstance(batch, list):
                raise UpstreamError('Expected a paginated GitLab list')
            items.extend(batch)
            if len(batch) < 100 or (stop_after and len(items) >= stop_after):
                return items
        raise UpstreamError('Pagination bound reached; results are incomplete')


def project_api(path):
    return GITLAB + 'projects/' + urllib.parse.quote(path, safe='')


def resolve(runtime, value, project=None):
    identity = canonical(value, project)
    if identity['backend'] == 'drupal':
        node = runtime.http(DRUPAL + f'node/{identity["id"]}.json')
        if node.get('new_url'):
            return canonical(node['new_url'])
    return identity


def issue_context(runtime, value, project=None):
    identity = resolve(runtime, value, project)
    missing = []
    try:
        issue = runtime.cli('issue:show', identity['ref'], '--with-comments', '--include-bot-comments')
    except UpstreamError as exc:
        missing.append(str(exc))
        issue = runtime.cli('issue:show', identity['ref'])
        missing.append('Full discussion unavailable; summary only')
    if identity['backend'] == 'drupal':
        identity['project'] = issue.get('field_project_machine_name') or identity.get('project')
        if not identity['project']:
            raise UpstreamError('Issue response lacks a project identity')
        identity['url'] = f'https://www.drupal.org/project/{identity["project"]}/issues/{identity["id"]}'
        comments = [{'id': c['cid'], 'url': identity['url'] + '#comment-' + str(c['cid']),
                     'author': c.get('author_name'), 'body': c.get('body_value'),
                     'created': c.get('created')} for c in issue.get('comments', [])]
        source = runtime.http(DRUPAL + f'node/{identity["id"]}.json')
        seen = {str(c['id']) for c in comments}
        # The CLI silently skips bot comments and failed/unparseable comment requests.
        # Recover every referenced source comment, not just the ones it returned.
        for ref in source.get('comments', []):
            cid = str(ref.get('id', ''))
            if not cid or cid in seen:
                continue
            try:
                record = runtime.http(DRUPAL + 'comment/' + cid + '.json')
                body = record.get('comment_body', {})
                if isinstance(body, dict):
                    body = body.get('value', body)
                comments.append({'id': cid, 'url': identity['url'] + '#comment-' + cid,
                                 'body': body, 'created': record.get('created'), 'source_record': record})
            except UpstreamError as exc:
                missing.append(f'Comment {cid}: {exc}')
        order = {str(ref.get('id')): index for index, ref in enumerate(source.get('comments', []))}
        comments.sort(key=lambda c: order.get(str(c['id']), len(order)))
        # Page preserves field changes, attachments and system messages omitted by CLI JSON.
        try:
            supplemental = runtime.http(identity['url'], text=True)
        except UpstreamError as exc:
            supplemental = None
            missing.append('Change/attachment page unavailable: ' + str(exc))
    else:
        comments = [{'id': c.get('id'), 'url': c.get('web_url') or identity['url'] + '#note_' + str(c['id']),
                     'author': c.get('author'), 'body': c.get('body'),
                     'created': c.get('created_at')} for c in issue.get('comments', [])]
        supplemental = None
        if not missing:
            try:
                notes = runtime.pages(project_api(identity['project_path']) + f'/issues/{identity["id"]}/notes',
                                      {'sort': 'asc', 'order_by': 'created_at'})
                comments = [{'id': n['id'], 'url': identity['url'] + '#note_' + str(n['id']),
                             'author': n['author']['username'], 'body': n['body'],
                             'system': n.get('system'), 'created': n['created_at']} for n in notes]
            except UpstreamError as exc:
                missing.append(str(exc))
    try:
        mrs = runtime.cli('mr:list', identity['ref'], '--state=all')
    except UpstreamError as exc:
        mrs = None
        missing.append(str(exc))
    try:
        fork = runtime.cli('issue:get-fork', identity['ref'])
    except UpstreamError as exc:
        fork = None
        missing.append(str(exc))
    attachments = attachment_inventory(identity, issue, comments, supplemental)
    return {'schema_version': 2, 'identity': identity, 'issue': issue, 'comments': comments,
            'supplemental_page': supplemental, 'attachments': attachments, 'merge_requests': mrs, 'fork': fork,
            'missing': missing, 'completeness': 'partial' if missing else 'retrieved; semantic analysis required',
            'root_cause': None}


def attachment_inventory(identity, issue, comments, page):
    found = {}
    texts = [(None, page or ''), (None, issue.get('description') or issue.get('body_value') or '')]
    texts.extend((c['id'], c.get('body') or '') for c in comments)
    for cid, text in texts:
        text = html.unescape(text if isinstance(text, str) else json.dumps(text))
        urls = set(re.findall(r'https://[^\s<>"\'\)\]]+', text))
        urls.update(urllib.parse.urljoin(identity['url'], u)
                    for u in re.findall(r'(?:href|src)=["\']([^"\']+)', text))
        for upload in re.findall(r'\]\((/uploads/[^\s\)]+)\)', text):
            if identity.get('project_path'):
                urls.add('https://git.drupalcode.org/' + identity['project_path'] + upload)
        for url in urls:
            parsed = urllib.parse.urlparse(url)
            if not ((parsed.hostname == 'www.drupal.org' and '/files/issues/' in parsed.path)
                    or (parsed.hostname == 'git.drupalcode.org' and '/uploads/' in parsed.path)):
                continue
            name = parsed.path.rsplit('/', 1)[-1]
            entry = found.setdefault(url, {'url': url, 'kind': 'interdiff' if 'interdiff' in name.lower()
                                       else 'patch' if name.endswith(('.patch', '.diff')) else 'attachment',
                                       'source_comment_ids': []})
            if cid is not None and cid not in entry['source_comment_ids']:
                entry['source_comment_ids'].append(cid)
    return [found[url] for url in sorted(found)]


def discover(runtime, project, status='Open', priority=None, component=None, limit=10, query=None, maintainer=None):
    if maintainer:
        if priority or component or query or status != 'Open':
            raise UpstreamError('Maintainer queue does not support those filters')
        return {'backend': 'cli', 'items': runtime.cli('maintainer:issues', maintainer)}
    if not project or not re.fullmatch(r'[a-z0-9_]+', project):
        raise UpstreamError('Use a Drupal project machine name')
    upstream = runtime.cli('project:issues', project, '--core=All', f'--limit={limit}')
    if upstream.get('project') == project and 'issues' in upstream:
        labels = []
        states = {'open': 'opened', 'active': 'opened', 'closed': 'closed', 'all': 'all'}
        state = states.get(status.lower(), 'opened')
        state_labels = {'needs review': 'state::needsReview', 'rtbc': 'state::rtbc',
                        'needs work': 'state::needsWork', 'postponed': 'state::postponed'}
        if status.lower() in state_labels:
            labels.append(state_labels[status.lower()])
        elif status.lower() not in states:
            raise UpstreamError('Unsupported migrated status; use an explicit supported state')
        if priority:
            labels.append('priority::' + priority.lower())
        if component:
            raise UpstreamError('Migrated component filtering requires a project-specific label mapping')
        params = {'state': state, 'order_by': 'updated_at', 'sort': 'desc'}
        if labels:
            params['labels'] = ','.join(labels)
        if query:
            params['search'] = query
            params['in'] = 'title'
        # Server ordering/filters first, then apply the user limit. Never filter an arbitrary ten.
        items = runtime.pages(project_api('project/' + project) + '/issues', params, stop_after=limit)
        return {'backend': 'gitlab', 'order': 'updated_desc', 'items': items[:limit], 'partial': False}
    warnings = []
    if query:
        # Capture the supported title-search command as well as exact legacy filter semantics.
        try:
            runtime.cli('issue:search', project, query, '--status=all', f'--limit={limit}')
        except UpstreamError as exc:
            warnings.append(str(exc))
    params = {'status': status, 'categories': 'All'}
    if component:
        params['component'] = component if '.' in component else component + '.module'
        params['categories'] = '1'
    if priority:
        params['priorities'] = priority
    if query:
        params['text'] = query
    body = runtime.http('https://www.drupal.org/project/issues/rss/' + project + '?' + urllib.parse.urlencode(params), text=True)
    return {'backend': 'rss', 'order': 'updated_desc', 'items': rss_module().parse_rss(body.encode())[:limit],
            'partial': False, 'upstream_warnings': warnings}


def rss_module():
    script = Path(__file__).parents[1] / 'skills/browse-drupal-issues/scripts/fetch_drupal_rss.py'
    spec = importlib.util.spec_from_file_location('drupal_rss', script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def pipeline_context(runtime, mr):
    path, iid = mr_reference(mr)
    api = project_api(path)
    metadata = runtime.http(api + f'/merge_requests/{iid}')
    warnings = []
    try:
        status = runtime.cli('mr:status', mr)
    except UpstreamError as exc:
        status = None
        warnings.append(str(exc))
    try:
        logs = runtime.cli('mr:logs', mr)
    except UpstreamError as exc:
        logs = {}
        warnings.append(str(exc))
    pipelines = runtime.pages(api + f'/merge_requests/{iid}/pipelines')
    if not pipelines:
        missing = ['Pipeline list disagrees with merge-request metadata'] if metadata.get('head_pipeline') else []
        return {'state': 'unknown' if missing else 'no_pipeline', 'merge_request': metadata,
                'jobs': [], 'missing': missing, 'upstream_warnings': warnings}
    pipeline = pipelines[0]
    # The pipeline owns the jobs. It may belong to the issue fork, not the MR target.
    owner = str(pipeline.get('project_id') or metadata['project_id'])
    detail = runtime.http(project_api(owner) + f'/pipelines/{pipeline["id"]}')
    jobs = runtime.pages(project_api(owner) + f'/pipelines/{pipeline["id"]}/jobs')
    failed = []
    missing = []
    for job in jobs:
        if job['status'] != 'failed':
            continue
        try:
            trace = runtime.http(project_api(owner) + f'/jobs/{job["id"]}/trace', text=True)
        except UpstreamError:
            try:
                trace = runtime.http(job['web_url'] + '/raw', text=True)
            except UpstreamError as exc:
                trace = None
                missing.append(str(exc))
        failed.append({'id': job['id'], 'name': job['name'], 'url': job['web_url'],
                       'allow_failure': job.get('allow_failure', False), 'trace': trace})
    head = metadata.get('sha')
    sha = detail.get('sha')
    relation = 'source_head' if head and sha == head else 'unverified'
    if relation == 'unverified' and sha and head:
        try:
            commit = runtime.http(project_api(owner) + '/repository/commits/' + sha)
            if head in commit.get('parent_ids', []):
                relation = 'merge_result_for_source_head'
            elif detail.get('source') == 'push' and detail.get('ref') == metadata.get('source_branch'):
                relation = 'stale_source_head'
        except UpstreamError as exc:
            missing.append(str(exc))
    if relation == 'unverified':
        missing.append('Pipeline revision relationship not verified; do not certify the current head')
    cli_names = {j['name'] for j in logs.get('failed_jobs', [])}
    return {'state': 'stale' if relation == 'stale_source_head' else detail['status'], 'pipeline': detail, 'merge_request': metadata,
            'revision_relation': relation, 'jobs': jobs, 'failed_jobs': failed,
            'cli_omitted_jobs': [j['name'] for j in failed if j['name'] not in cli_names],
            'cli_status': status, 'upstream_warnings': warnings, 'missing': missing, 'complete': not missing}


def mr_context(runtime, mr):
    path, iid = mr_reference(mr)
    api = project_api(path) + f'/merge_requests/{iid}'
    missing = []
    result = {'schema_version': 2, 'url': f'https://git.drupalcode.org/{path}/-/merge_requests/{iid}'}
    for key, command, extra in [('metadata', 'mr:show', ['--with-comments']), ('files', 'mr:files', []), ('diff', 'mr:diff', [])]:
        try:
            result[key] = runtime.cli(command, mr, *extra)
        except UpstreamError as exc:
            missing.append(str(exc))
            result[key] = None
    try:
        result['discussions'] = runtime.pages(api + '/discussions')
    except UpstreamError as exc:
        result['discussions'] = []
        missing.append('Review discussions unavailable: ' + str(exc))
    result['unresolved'] = [note for discussion in result['discussions'] for note in discussion['notes']
                            if note.get('resolvable') and not note.get('resolved')]
    try:
        result['pipeline'] = pipeline_context(runtime, mr)
    except UpstreamError as exc:
        result['pipeline'] = {'state': 'unavailable', 'missing': [str(exc)], 'complete': False}
    result['missing'] = missing + result['pipeline']['missing']
    return result


def artifact_dir(root, identity):
    project = identity.get('project')
    if not project or not re.fullmatch(r'[a-z0-9_]+', project):
        raise UpstreamError('Artifact identity needs an explicit project')
    return Path(root) / 'analysis-reports/drupal-issue' / project / str(int(identity['id']))


def analysis_path(root, identity):
    current = artifact_dir(root, identity) / 'analysis.json'
    if current.exists():
        return current
    legacy = Path(root) / 'analysis-reports/drupal-issue' / str(int(identity['id'])) / 'analysis.json'
    if legacy.exists():
        data = json.loads(legacy.read_text())
        if data.get('project') == identity['project']:
            return legacy
    return current


def remote_write(runtime, command, args, gate_body=None):
    args = normalize_files(args)
    if not args or args[0].startswith('-'):
        raise UpstreamError('Remote operations require an explicit issue/work-item reference')
    identity = resolve(runtime, args[0])
    if identity['backend'] != 'gitlab':
        raise UpstreamError('These write commands require a migrated GitLab work item')
    args = [identity['ref'], *args[1:]]
    projects = [identity['project_path']]
    if command in ('issue:fork', 'issue:get-access'):
        fork = runtime.cli('issue:get-fork', identity['ref'])
        if command == 'issue:fork' and fork.get('exists'):
            return {'state': 'already_exists', 'fork': fork}
        if command == 'issue:get-access':
            if not fork.get('exists'):
                raise UpstreamError('No fork exists; fork creation requires its own authority')
            project = runtime.http(project_api(fork['gitlab_project_path']))
            permissions = project.get('permissions', {})
            if any((permissions.get(key) or {}).get('access_level', 0) >= 30
                   for key in ('project_access', 'group_access')):
                return {'state': 'already_has_access', 'fork': fork}
        expected = '/do:fork' if command == 'issue:fork' else '/do:access'
        validate_post(gate_body, projects, expected)
        result = runtime.cli(command, *args, write=True)
        verification = runtime.cli('issue:get-fork', identity['ref'], '--no-cache')
        return {'state': 'requested; verify asynchronous result before retry',
                'response': result, 'verification': verification}
    if command == 'issue:comment':
        files = [arg.split('=', 1)[1] for arg in args[1:] if arg.startswith('--file=')]
        if len(files) != 1 or len(args) != 2:
            raise UpstreamError('Comments require exactly one --file body with a matching gate; inline messages are refused')
        validate_post(files[0], projects)
    elif command == 'issue:relate':
        if len(args) < 2:
            raise UpstreamError('Relate requires an explicit target work item')
        target = resolve(runtime, args[1])
        if target['backend'] != 'gitlab':
            raise UpstreamError('Relate target must be a migrated GitLab work item')
        args[1] = target['ref']
        projects.append(target['project_path'])
        validate_post(gate_body, projects, ' '.join([command, *args]))
    else:
        action = command.split(':', 1)[1]
        values = args[1:] or (['me'] if action in ('assign', 'unassign') else [])
        if not values or any(value.startswith('-') for value in values):
            raise UpstreamError('Explicit users/labels are required; extra write options are not supported')
        if action in ('assign', 'unassign', 'reassign'):
            values = [v.strip().lstrip('@') for v in values]
            values = [v if v == 'me' else '@' + v for v in values]
        else:
            values = ['~' + v.strip().lstrip('~') for v in values]
        validate_post(gate_body, projects, '/do:' + action + ' ' + ' '.join(values))
    return runtime.cli(command, *args, write=True)


def load_runtime(args):
    config_path = Path(args.config).expanduser()
    config = json.loads(config_path.read_text()) if config_path.exists() else {}
    settings = config.get('drupal_org', {}).get('cli', {})
    for project in config.get('projects', []):
        if any(Path.cwd().is_relative_to(Path(p).expanduser()) for p in project.get('cwd_patterns', [])):
            settings = dict(settings, **project.get('drupal_org_cli', {}))
            break
    worktree = args.runtime_worktree or settings.get('runtime_worktree')
    if not worktree:
        raise UpstreamError('Configure drupal_org.cli.runtime_worktree or pass --runtime-worktree')
    return Runtime(worktree, args.phar or settings.get('phar', '/mnt/ddev_config/drupalorg/' + VERSION + '/drupalorg.phar'), args.output)


def install(worktree):
    import ssl
    import urllib.request
    root = runtime_guard(worktree)
    dest = root / '.ddev/drupalorg' / VERSION / 'drupalorg.phar'
    context = ssl.create_default_context(cafile='/etc/ssl/cert.pem' if Path('/etc/ssl/cert.pem').exists() else None)
    with urllib.request.urlopen(f'https://github.com/mglaman/drupalorg-cli/releases/download/{VERSION}/drupalorg.phar', timeout=45, context=context) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise UpstreamError('Release checksum mismatch; no executable installed')
    dest.parent.mkdir(parents=True, exist_ok=True)
    # Keep our own local ignore rather than editing DDEV's generated configuration.
    ignore = root / '.ddev/drupalorg/.gitignore'
    old = ignore.read_text() if ignore.exists() else ''
    if '*' not in old.splitlines():
        ignore.write_text(old.rstrip('\n') + '\n*\n')
    dest.write_bytes(data)
    return {'version': VERSION, 'sha256': SHA256, 'path': str(dest),
            'container_path': '/mnt/ddev_config/drupalorg/' + VERSION + '/drupalorg.phar'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', default='~/.claude/drupal-lab.json')
    parser.add_argument('--runtime-worktree')
    parser.add_argument('--phar')
    parser.add_argument('--output', help='Fresh evidence/result directory; never reuse a previous run')
    sub = parser.add_subparsers(dest='operation', required=True)
    sub.add_parser('install')
    sub.add_parser('doctor')
    for operation in ('issues', 'search'):
        command = sub.add_parser(operation)
        command.add_argument('project', nargs='?')
        command.add_argument('--query')
        command.add_argument('--maintainer')
        command.add_argument('--status', default='Open')
        command.add_argument('--priority')
        command.add_argument('--component')
        command.add_argument('--limit', type=int, default=10)
    for operation in ('issue-context', 'fork-info', 'merge-request-context', 'pipeline-context'):
        command = sub.add_parser(operation)
        command.add_argument('ref')
    for operation in ('releases', 'release-notes', 'contains'):
        command = sub.add_parser(operation)
        command.add_argument('project')
        if operation != 'releases':
            command.add_argument('value')
    command = sub.add_parser('write')
    command.add_argument('--authorized', action='store_true', help='Existing task and posting-policy authority is required')
    command.add_argument('--gate-body', help='File with the exact slash-command/action text and adjacent .gate.json')
    command.add_argument('command', choices=sorted(WRITES))
    command.add_argument('args', nargs=argparse.REMAINDER)
    args = parser.parse_args()
    try:
        if args.output and Path(args.output).exists():
            raise UpstreamError('Choose a fresh output directory; preserve previous evidence')
        if args.operation == 'install':
            if not args.runtime_worktree:
                raise UpstreamError('Install requires --runtime-worktree for the destination')
            result = install(args.runtime_worktree)
        else:
            runtime = load_runtime(args)
            if args.operation == 'doctor':
                catalog = runtime.cli('list')
                result = {'available_commands': [c['name'] for c in catalog['commands']],
                          'tested_version': VERSION, 'host_credential_available': bool(runtime.token),
                          'runtime_worktree': str(runtime.worktree)}
            elif args.operation in ('issues', 'search'):
                if args.limit < 1 or args.limit > 100:
                    raise UpstreamError('Limit must be between 1 and 100')
                if args.operation == 'search' and not args.query:
                    raise UpstreamError('Search requires --query')
                project = args.project or rss_module().detect_project_name()
                result = discover(runtime, project, args.status, args.priority, args.component, args.limit, args.query, args.maintainer)
            elif args.operation == 'issue-context':
                result = issue_context(runtime, args.ref)
            elif args.operation == 'fork-info':
                identity = resolve(runtime, args.ref)
                result = {'identity': identity, 'fork': runtime.cli('issue:get-fork', identity['ref'])}
            elif args.operation == 'merge-request-context':
                result = mr_context(runtime, args.ref)
            elif args.operation == 'pipeline-context':
                result = pipeline_context(runtime, args.ref)
            elif args.operation in ('releases', 'release-notes', 'contains'):
                command = 'project:' + args.operation
                result = runtime.cli(command, args.project, *([args.value] if hasattr(args, 'value') else []))
            elif args.operation == 'write':
                if not args.authorized:
                    raise UpstreamError('Remote writes require existing explicit authority and --authorized')
                if '--file=-' in args.args:
                    raise UpstreamError('Use an explicit comment file, transported through the configured runtime; stdin is reserved for the runner')
                result = remote_write(runtime, args.command, args.args, args.gate_body)
            if args.output:
                target = Path(args.output)
                target.mkdir(parents=True, mode=0o700, exist_ok=True)
                (target / 'result.json').write_text(json.dumps(result, indent=2) + '\n')
        if args.output and args.operation != 'install':
            print(json.dumps({'result': str(Path(args.output) / 'result.json'), 'operation': args.operation,
                              'identity': result.get('identity'), 'state': result.get('state'),
                              'missing': result.get('missing', []), 'retrieval_steps': len(runtime.receipts)}, indent=2))
        else:
            print(json.dumps(result, indent=2))
    except (UpstreamError, OSError, subprocess.SubprocessError, ValueError, KeyError) as exc:
        print(json.dumps({'state': 'error', 'error': str(exc)}), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
